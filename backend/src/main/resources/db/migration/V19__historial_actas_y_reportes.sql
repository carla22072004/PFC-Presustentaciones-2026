    (22, 'ACTAS_VER',           'Ver actas',             'Actas', 'Listar y consultar el detalle de las actas de pre-sustentación'),
    (23, 'ACTAS_VER_PROPIAS',   'Ver actas propias',     'Actas', 'Que un docente vea las actas de las pre-sustentaciones en las que es tutor o jurado'),
    (24, 'ACTA_HISTORIAL_VER',  'Ver historial de acta', 'Actas', 'Consultar el historial de cambios de estado de un acta'),
    (25, 'ACTA_ESTADO_CAMBIAR', 'Cambiar estado de acta','Actas', 'Cambiar el estado de un acta (revisar, observar, finalizar, anular) según las reglas del proceso'),
    (26, 'ACTAS_GESTIONAR',     'Gestionar actas',       'Actas', 'Gestión administrativa completa de actas: buscar, filtrar, corregir y cambiar estado')
