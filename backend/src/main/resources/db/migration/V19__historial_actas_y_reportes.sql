WHERE p.codigo IN ('ACTAS_VER','ACTAS_VER_PROPIAS','ACTA_HISTORIAL_VER','ACTA_ESTADO_CAMBIAR','ACTAS_GESTIONAR')
ON CONFLICT DO NOTHING;

-- COORDINADOR: ver, ver historial y cambiar estado (revisión académica);
-- NO gestión administrativa completa (ACTAS_GESTIONAR queda solo para ADMIN).
INSERT INTO presus.rol_permisos (rol_id, permiso_id)
SELECT 3, p.id FROM presus.permisos p
WHERE p.codigo IN ('ACTAS_VER','ACTA_HISTORIAL_VER','ACTA_ESTADO_CAMBIAR')
ON CONFLICT DO NOTHING;

-- DOCENTE: solo sus propias actas y el historial de esas (el service aplica el
-- filtro por propiedad; el permiso solo habilita la funcionalidad).
INSERT INTO presus.rol_permisos (rol_id, permiso_id)
SELECT 2, p.id FROM presus.permisos p
WHERE p.codigo IN ('ACTAS_VER_PROPIAS','ACTA_HISTORIAL_VER')
ON CONFLICT DO NOTHING;

